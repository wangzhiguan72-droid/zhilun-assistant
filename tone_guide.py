"""
语气规约（v1.7 · 规划§四 P1 人味增强 / ROADMAP「降低 AI 味」）
==============================================================
把 ROADMAP 里那句模糊的「降低 AI 味」落成**可执行、可测试**的规则。

ROADMAP 原文要求（P1 人味增强）：
    「规则化模板：拆长句、删空泛总结、补细节引导词；**不做"绕过检测"类功能**」

设计边界（重要）：
    · 本模块**只规范"怎么写"**，不改任何统计结论、不动证据台账。
    · 它**不是**"绕过 AI 检测"工具 —— ROADMAP 明确禁止该类功能。
      目标是让中文读起来像人写的学术文本，而非规避检测。
    · 纯规则、零 LLM、无副作用：任何入口都能安全调用。

两个用途：
    1. `TONE_RULES`：注入 LLM 的冻结 system prompt，把"避免 AI 腔"讲成**具体禁令**
       （旧 prompt 只说了"避免口语化和 AI 腔"，模型只能猜）。
    2. `find_ai_speak(text)`：**生成后**的规则化体检，命中就给出可替换建议；
       供测试 / 运维观测使用（不擅自改写用户的文字）。

⚠️ 修改 TONE_RULES 的措辞 = 改变冻结 prompt = 必须 bump 相关 PROMPT_VERSION。
"""
from __future__ import annotations

import re

# ---------------------------------------------------------------------------
# 一、给 LLM 的明确禁令（替换旧 prompt 里含糊的"避免 AI 腔"）
# ---------------------------------------------------------------------------
# 每条都是**可判定**的具体行为，不是形容词。
TONE_RULES = (
    "中文表达要求（务必遵守，目标：读起来像同行写的，不像机器生成的）：\n"
    "1. 拆长句：一句话只讲一件事。避免「不仅…而且…」「在…的基础上，进一步…」"
    "这类套式连接；转折用短句断开。\n"
    "2. 删空泛总结：禁止「具有重要意义」「提供了有力支撑」「具有较高的学术价值」"
    "「为后续研究奠定了坚实基础」等无信息量的收尾。\n"
    "   若一句话删掉后不影响读者判断，就别写它。\n"
    "3. 不堆排比与形容词：不要「高效、准确、稳定」三连；"
    "改为给出具体数字或条件（如「在 n=120 时 p<0.001」）。\n"
    "4. 结论句必须带具体依据：写「存在显著差异」时，同句给出统计量与样本量；"
    "不要只写「结果良好」「影响显著」。\n"
    "5. 少用第一人称套话与情绪词：不写「值得注意的是」「不难看出」「显而易见」。\n"
    "6. 术语前后一致：同一个概念全文用同一个词，不要同义替换（T 检验 / t 检验 混用）。\n"
    "7. 不写小标题式的废话开头（如「一、方法概述」后接一句「方法的选择至关重要」）。\n"
)

# 供 paper_check 用的加强版（审稿语境，建议要能直接落地）
TONE_RULES_REVIEW = (
    TONE_RULES
    + "8. 建议必须可执行：写「补充效应量（Cohen's d）」而不是「建议完善统计报告」；"
    "能点名具体检验/指标就点名。\n"
)

# ---------------------------------------------------------------------------
# 二、AI 腔检测（规则化体检，供观测 / 测试）
# ---------------------------------------------------------------------------
# (正则, 类别, 说明)
AI_SPEAK_PATTERNS: list[tuple[str, str, str]] = [
    # 空泛总结
    (r"具有重要意义", "空泛总结", "无信息量，删掉不影响判断"),
    (r"具有(较高|重要)的?(学术|理论|实践|应用)?价值", "空泛总结", "空泛评价"),
    (r"提供了?(有力|坚实|重要)的?(支撑|依据|基础|保障)", "空泛总结", "空泛支撑"),
    (r"奠定了?(坚实|良好|重要)的?基础", "空泛总结", "空泛收尾"),
    (r"(为|对)(后续|未来|进一步)(的)?(研究|工作|实践)(提供|奠定|指明)", "空泛总结",
     "空头展望"),
    (r"综上所述[，,]", "空泛总结", "套式收尾，可直接删"),
    (r"总体(来看|而言)[，,]", "空泛总结", "套式过渡"),
    (r"不难(看出|发现)|显而易见|众所周知", "套话", "启发性套话"),
    (r"值得注意的是[，,]?", "套话", "过度使用会稀释重点"),
    # 堆砌排比 / 形容词三连
    (r"(高效|准确|稳定|可靠|全面|系统|科学)(、|\s*,\s*)?(高效|准确|稳定|可靠|全面|系统|科学)"
     r"(、|\s*,\s*)?(高效|准确|稳定|可靠|全面|系统|科学)", "排比堆砌", "形容词三连，改给数字"),
    (r"具有(很强|很强|极强|突出)的", "排比堆砌", "空泛程度副词"),
    # 套式连接
    (r"不仅.{0,20}而且", "长句套式", "拆成两句"),
    (r"在.{0,15}的?(基础|前提)上[，,]?\s*(进一步|进而)", "长句套式", "拆成两句"),
    (r"随着.{0,20}的?(不断|持续)(发展|深入|推进)", "长句套式", "套式开头"),
    (r"旨在|致力于", "长句套式", "机器味动词，改直述"),
    (r"赋能|抓手|闭环打?通|生态化", "互联网黑话", "非学术用语"),
    # 情绪 / 主观
    (r"(令人|值得)(惊讶|欣喜|振奋)的是", "情绪词", "学术文本不宜带情绪"),
    (r"非常(重要|关键|显著)|极为(重要|关键)", "情绪词", "程度词空泛"),
]

# 编译一次（性能 + 复用）
_COMPILED: list[tuple[re.Pattern[str], str, str]] = [
    (re.compile(p), cat, note) for p, cat, note in AI_SPEAK_PATTERNS
]


def find_ai_speak(text: str) -> list[dict]:
    """扫描文本里的 AI 腔，返回命中列表。

    出参: [{"phrase": 命中的词, "category": 类别, "note": 说明,
            "count": 出现次数, "index": 首次位置}, ...]

    纯观测，**不改写文本** —— 是否采纳由人决定。
    """
    if not text:
        return []
    hits: list[dict] = []
    for rx, cat, note in _COMPILED:
        ms = list(rx.finditer(text))
        if not ms:
            continue
        hits.append({
            "phrase": ms[0].group(0),
            "category": cat,
            "note": note,
            "count": len(ms),
            "index": ms[0].start(),
        })
    # 按首次出现位置排序，方便人工顺着读
    hits.sort(key=lambda h: h["index"])
    return hits


def ai_speak_score(text: str) -> dict:
    """给一段文本打个"AI 味"体检分（供观测 / 报告）。"""
    hits = find_ai_speak(text)
    total = sum(h["count"] for h in hits)
    # 每千字命中数（可比性更好的密度指标）
    n_chars = max(len(text or ""), 1)
    density = round(total * 1000.0 / n_chars, 2)
    cats: dict[str, int] = {}
    for h in hits:
        cats[h["category"]] = cats.get(h["category"], 0) + h["count"]
    return {
        "total_hits": total,
        "density_per_1k": density,
        "by_category": cats,
        "hits": hits,
    }


def has_ai_speak(text: str, threshold: int = 1) -> bool:
    """是否达到"明显 AI 腔"阈值（默认命中 1 处即算，用于测试断言）。"""
    return sum(h["count"] for h in find_ai_speak(text)) >= threshold

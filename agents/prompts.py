    prefix = build_paper_check_prefix(paper_text)     # 同篇论文只算一次，可缓存
    prompt = build_paper_check_prompt(prefix, "审计第 3.2 节的统计方法选择")
    router.complete("paper_check", prompt, system=PAPER_CHECK_SYSTEM)
